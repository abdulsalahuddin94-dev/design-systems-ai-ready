"""DESIGN.md + AGENTS.md for a finished design system, so any AI coding tool builds UI from it.

Usage:  python tools/design_md.py <DS folder>            write <folder>/DESIGN.md and the managed block in <folder>/AGENTS.md
        python tools/design_md.py <DS folder> --check    exit 1 if DESIGN.md is missing or older than the data files

Idea and section order from MUZEEBURRAHAMAN/design-system-skills `ds-design-md` + `guides/design-md.md` (MIT) and the
google-labs-code/design.md format (YAML front matter with tokens, then Overview, Colors, Typography, Layout,
Elevation & Depth, Shapes, Components, Do's and Don'ts); the AGENTS.md block follows natdexterra/work-with-design-systems
`references/build/code-export.md` (MIT). Unlike those, this reads only our knowledge base (data/tokens.json,
data/component-registry.json, data/rules.json, Project_Brief.md), never Figma, so it costs no Figma calls: run it after
`build_tokens.py` and the registry are current (Design_System_Intake_Skill section 11 step 3).

Hand-written text survives a rerun: anything between `<!-- manual:start -->` and `<!-- manual:end -->` in the
Overview and Do's and Don'ts sections is kept. Everything else is regenerated. Names are exactly as in Figma.
"""
import json
import pathlib
import re
import sys

START, END = "<!-- manual:start -->", "<!-- manual:end -->"
AG_START, AG_END = "<!-- design-system:start -->", "<!-- design-system:end -->"


def read_json(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return {}


def yq(value):
    """YAML-safe scalar."""
    if isinstance(value, (int, float)):
        return str(round(value, 3)).rstrip("0").rstrip(".") if isinstance(value, float) else str(value)
    return json.dumps(str(value), ensure_ascii=False)


def key(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def by_role(tokens, role):
    cols = [c for c, meta in tokens.get("collections", {}).items() if meta.get("role") == role]
    return [v for v in tokens.get("variables", {}).values() if v.get("collection") in cols]


def first_value(var):
    vals = var.get("resolved") or var.get("values") or {}
    for v in vals.values():
        if not isinstance(v, dict):
            return v
    return None


def manual_blocks(old):
    """Kept hand-written blocks, by the heading they sit under."""
    kept, heading = {}, None
    for part in re.split(r"(?m)^(## .+)$", old):
        if part.startswith("## "):
            heading = part.strip()
        elif heading and START in part and END in part:
            kept[heading] = part[part.index(START):part.index(END) + len(END)]
    return kept


def manual(kept, heading, default):
    return kept.get(heading) or f"{START}\n{default}\n{END}"


def build(folder):
    tokens = read_json(folder / "data" / "tokens.json")
    reg = read_json(folder / "data" / "component-registry.json")
    rules = read_json(folder / "data" / "rules.json")
    meta = tokens.get("meta", {})
    platform = meta.get("platform") or reg.get("meta", {}).get("platform") or "Web"
    name = meta.get("figma_file") or folder.name
    semantic = sorted(by_role(tokens, "semantic"), key=lambda v: v["name"])
    spacing = sorted(by_role(tokens, "spacing"), key=lambda v: (first_value(v) or 0) if isinstance(first_value(v), (int, float)) else 0)
    radius = sorted(by_role(tokens, "radius"), key=lambda v: (first_value(v) or 0) if isinstance(first_value(v), (int, float)) else 0)
    typo = by_role(tokens, "typography")
    comps = reg.get("components", [])
    a11y = rules.get("accessibility", {})

    # ---- front matter (machine-readable, google-labs-code/design.md shape)
    fm = ["---", f"name: {yq(name)}", f"platform: {yq(platform)}", "colors:"]
    for v in semantic:
        if v.get("type") != "color":
            continue
        res = v.get("resolved") or {}
        if res:
            modes = ", ".join(f"{m}: {yq(h)}" for m, h in res.items())
            fm.append(f"  {key(v['name'])}: {{ {modes} }}")
    fm.append("spacing:")
    for v in spacing:
        val = first_value(v)
        if isinstance(val, (int, float)):
            fm.append(f"  {key(v['name'])}: {yq(val)}")
    fm.append("rounding:")
    for v in radius:
        val = first_value(v)
        if isinstance(val, (int, float)):
            fm.append(f"  {key(v['name'])}: {yq(val)}")
    fm.append("---")

    old = (folder / "DESIGN.md").read_text(encoding="utf-8") if (folder / "DESIGN.md").exists() else ""
    kept = manual_blocks(old)
    out = fm + ["", f"# {name}", "",
                "> Generated by `tools/design_md.py` from this folder's `data/` files. Figma is the source: change Figma, resync the data, rerun. Only the blocks between the manual markers are hand-written.", ""]

    out += ["## Overview", "", manual(kept, "## Overview",
            f"{platform} design system. Describe the look in 2-4 sentences: mood, density, what makes it recognisable."), ""]

    out += ["## Colors", "", "Use Semantic tokens only; Primitives are raw values that Semantic tokens alias. Never type a hex value.", "",
            "| Token | " + " | ".join(next(iter([list((v.get('resolved') or {}).keys()) for v in semantic if v.get('resolved')]), ["Value"])) + " | Use |",
            ]
    modes = next(iter([list((v.get("resolved") or {}).keys()) for v in semantic if v.get("resolved")]), ["Value"])
    out.append("|" + "---|" * (len(modes) + 2))
    for v in semantic:
        if v.get("type") != "color":
            continue
        res = v.get("resolved") or {}
        out.append(f"| `{v['name']}` | " + " | ".join(str(res.get(m, "")) for m in modes) + f" | {v.get('description', '')} |")
    out.append("")

    out += ["## Typography", ""]
    ts = reg.get("text_styles")
    if isinstance(ts, dict) and ts.get("naming"):
        out.append(f"Text styles: {ts.get('count', '?')} styles named `{ts['naming']}`. Always apply a text style; never set font, size or weight by hand.")
    elif isinstance(ts, list) and ts:
        out.append("Text styles: " + ", ".join(f"`{s if isinstance(s, str) else s.get('name')}`" for s in ts[:40]))
    fam = [v for v in typo if "family" in v["name"].lower()]
    if fam:
        out.append("Font family: " + ", ".join(f"`{v['name']}` = {first_value(v)}" for v in fam))
    sizes = [v for v in typo if "size" in v["name"].lower() and isinstance(first_value(v), (int, float))]
    if sizes:
        out.append("Sizes: " + ", ".join(f"`{v['name']}` {first_value(v)}" for v in sorted(sizes, key=first_value)))
    out.append("")

    out += ["## Layout", ""]
    sp = rules.get("spacing", {})
    if sp.get("base_unit"):
        out.append(f"Base unit {sp['base_unit']}. {sp.get('rule', '')}".strip())
    if spacing:
        out.append("Spacing tokens: " + ", ".join(f"`{v['name']}` {first_value(v)}" for v in spacing))
    bp = rules.get("breakpoints")
    if bp:
        out.append(f"Breakpoints: {json.dumps(bp, ensure_ascii=False)}")
    out.append("")

    out += ["## Elevation & Depth", ""]
    eff = reg.get("effect_styles") or []
    out.append(("Effect styles: " + ", ".join(f"`{e if isinstance(e, str) else e.get('name')}`" for e in eff)) if eff else "No effect styles.")
    out.append("")

    out += ["## Shapes", ""]
    if radius:
        out.append("Radius tokens: " + ", ".join(f"`{v['name']}` {first_value(v)}" + (f" ({v['description']})" if v.get("description") else "") for v in radius))
    usage = rules.get("radius", {}).get("usage")
    if usage:
        out.append("Usage: " + "; ".join(f"{k}: {val}" for k, val in usage.items()))
    out.append("")

    out += ["## Components", "", "Build UI only from these components (names exactly as in Figma and in code). Tier: Atom < Molecule < Organism < Pattern.", "",
            "| Component | Group | Tier | Use | Variants |", "|---|---|---|---|---|"]
    for c in sorted(comps, key=lambda c: (c.get("group", ""), c.get("name", ""))):
        d = c.get("docs") or {}
        use = (d.get("overview") or c.get("use") or "").replace("|", "/")
        variants = "; ".join(f"{k}: {', '.join(map(str, v))}" for k, v in (c.get("variants") or {}).items()).replace("|", "/")
        out.append(f"| {c.get('name')} | {c.get('group', '')} | {c.get('tier', '')} | {use} | {variants} |")
    out.append("")

    out += ["## Do's and Don'ts", ""]
    base = []
    cm = a11y.get("contrast_min", {})
    if cm:
        base.append(f"- Do keep contrast at least {cm.get('text', 4.5)}:1 for text and {cm.get('ui_boundary', 3)}:1 for UI boundaries, in every color mode.")
    tt = a11y.get("touch_target_min")
    if tt:
        base.append(f"- Do make touch targets at least {tt.get('recommended', tt) if isinstance(tt, dict) else tt}px.")
    base += ["- Do bind every color, spacing, radius and type value to a token or style.",
             "- Do use Radio for 2 to 6 options and Select for 7 or more.",
             "- Don't create a component when one in the table covers the need; compose from lower tiers instead.",
             "- Don't hardcode hex, px or font values, and don't detach instances."]
    for c in comps:
        for a in (c.get("docs") or {}).get("avoid", []):
            base.append(f"- Don't ({c['name']}): {a.rstrip('.')}.")
    # rules.json > off_limits are Figma build rules for this workflow (detaching, page placement, installs), not
    # rules for code; the two that matter in code are in the lines above.
    out += base + ["", manual(kept, "## Do's and Don'ts", "Add the product's own rules here (they survive a rerun)."), ""]

    out += ["## For AI agents", "",
            "- Exact values: `data/tokens.json` (keys `<Collection>::<name>`), components and slots: `data/component-registry.json`, rules: `data/rules.json`.",
            "- Usage per component: `Component_Skills/*/references/components.md`; foundations: `Foundation_Skill/SKILL.md`.",
            "- With a Storybook: read its MCP or `storybook/` for props before writing UI.", ""]
    return "\n".join(out)


def agents_block():
    return "\n".join([AG_START, "## Design system (generated by tools/design_md.py)", "",
                      "Before writing UI, read `DESIGN.md` in this folder. Use only its components and tokens, with the exact names; "
                      "never hardcode colors, spacing, radius or fonts. Exact values are in `data/tokens.json`, components and slots in "
                      "`data/component-registry.json`.", AG_END])


def write_agents(folder):
    path = folder / "AGENTS.md"
    text = path.read_text(encoding="utf-8") if path.exists() else "# Agent instructions\n"
    if AG_START in text and AG_END in text:
        text = text[:text.index(AG_START)] + agents_block() + text[text.index(AG_END) + len(AG_END):]
    else:
        text = text.rstrip("\n") + "\n\n" + agents_block() + "\n"
    path.write_text(text, encoding="utf-8")


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__)
        return 2
    folder = pathlib.Path(args[0])
    if not (folder / "data" / "tokens.json").exists():
        print(f"No {folder / 'data' / 'tokens.json'}: run tools/build_tokens.py first.")
        return 2
    design = folder / "DESIGN.md"
    if "--check" in sys.argv:
        newest = max(p.stat().st_mtime for p in (folder / "data").glob("*.json"))
        if not design.exists() or design.stat().st_mtime < newest:
            print("DESIGN.md is missing or older than data/*.json: run python tools/design_md.py " + str(folder))
            return 1
        print("DESIGN.md is current.")
        return 0
    design.write_text(build(folder), encoding="utf-8")
    write_agents(folder)
    print(f"Wrote {design} and the design-system block in {folder / 'AGENTS.md'}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
