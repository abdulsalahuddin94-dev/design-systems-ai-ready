"""Live Prototype (Screens_Handoff_Skill): UI strings of the exported screens, for the AR switch and the Code panel.

Usage (from the Root; tools/screen_code.py also runs it):
  python tools/prototype_strings.py "My Projects/<Project>"

Reads   <project>/prototype/data/screens.json
        <project>/data/strings/content.json  (texts that are content, not UI: song, artist, playlist and podcast names,
                                              episode descriptions; they stay as they are in every language)
        <project>/data/strings/ar.json       (the translations, edited by people; never overwritten)
Writes  <project>/data/strings/en.json       (every UI string by a readable key, with the screens that use it)
        <project>/prototype/public/strings/ar.json (the runtime map English text -> Arabic text for the prototype)

Keys are derived from the English text (Your Library -> your_library; EXPLORE -> explore_caps when Explore exists).
A key missing in ar.json is listed as untranslated; the prototype then shows the English text.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_prototype import base_name, slugify  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def load(path, default=None):
    p = Path(path)
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else default


def texts_of(node, out, screen):
    """Every text a screen shows: TEXT properties and nested text layers of its instances."""
    for v in (node.get("p") or {}).values():
        if isinstance(v, str) and v.strip():
            out.setdefault(v, set()).add(screen)
    for v in (node.get("tx") or {}).values():
        if isinstance(v, str) and v.strip():
            out.setdefault(v, set()).add(screen)
    for c in node.get("ch", []):
        texts_of(c, out, screen)


def make_key(text, taken):
    words = re.findall(r"[A-Za-z0-9]+", text.lower())[:6]
    key = "_".join(words) or "text"
    if key[0].isdigit():
        key = "t_" + key
    base = key
    if key in taken and taken[key] != text:
        key = base + ("_caps" if text.isupper() else "_2")
    n = 3
    while key in taken and taken[key] != text:
        key, n = f"{base}_{n}", n + 1
    taken[key] = text
    return key


def build(project):
    project = Path(project).resolve()
    data = load(project / "prototype" / "data" / "screens.json")
    sdir = project / "data" / "strings"
    sdir.mkdir(parents=True, exist_ok=True)
    content = set(load(sdir / "content.json", {"texts": []}).get("texts", []))
    found = {}
    prefix = (data.get("page") or "") + " / "
    for s in data["screens"]:
        if not s["n"].lower().endswith("dark") and any(x["n"].lower().endswith("dark") for x in data["screens"]):
            continue  # Light frames repeat the Dark texts
        b = base_name(s["n"])
        b = b[len(prefix):] if b.startswith(prefix) else b
        texts_of(s["tree"], found, slugify(b))
    ui = {t: sc for t, sc in found.items() if t not in content and not re.fullmatch(r"[\d:]+", t.strip())}
    # Mixed-case text first, so "Explore" keeps the plain key and "EXPLORE" gets _caps.
    taken, keys = {}, {}
    for t in sorted(ui, key=lambda x: (x.isupper(), x.lower())):
        keys[t] = make_key(t, taken)
    en = {"_note": "Generated by tools/prototype_strings.py from the Figma export. UI strings only; content (names, "
                   "descriptions) is listed in content.json. Do not edit: translate in ar.json.",
          "strings": {keys[t]: t for t in sorted(ui, key=lambda x: keys[x])},
          "screens": {keys[t]: sorted(ui[t]) for t in sorted(ui, key=lambda x: keys[x])}}
    (sdir / "en.json").write_text(json.dumps(en, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    ar = load(sdir / "ar.json", {"strings": {}})
    tr = ar.get("strings", {})
    runtime = {t: tr[k] for t, k in keys.items() if k in tr}
    pub = project / "prototype" / "public" / "strings"
    pub.mkdir(parents=True, exist_ok=True)
    (pub / "ar.json").write_text(json.dumps(runtime, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    missing = sorted(k for k in en["strings"] if k not in tr)
    return {"keys": {t: k for t, k in keys.items()}, "en": en["strings"], "ar": tr, "missing": missing,
            "content": sorted(content & set(found))}


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    arg = Path(sys.argv[1])
    r = build(arg if arg.is_absolute() else ROOT / arg)
    print(f"UI strings: {len(r['en'])} (Arabic {len(r['en']) - len(r['missing'])}, untranslated {len(r['missing'])}); content kept as is: {len(r['content'])}")
    for k in r["missing"][:30]:
        print("  untranslated: " + k)
