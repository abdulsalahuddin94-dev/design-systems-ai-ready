"""Build Style_Library/styles.json, the index of the style library (intake 0.3e, the dashboard's Style library).

Usage (from the Root):
  python tools/build_style_index.py                        rebuild the index from Style_Library/*/DESIGN.md
  python tools/build_style_index.py --source <folder>      first copy <folder>/<slug>/DESIGN.md into
                                                           Style_Library/<slug>/DESIGN.md (unchanged), then rebuild
  python tools/build_style_index.py --check                exit 1 when styles.json is out of date (CI, /contribute)

Each entry: slug, title, name, category, description, inspired_by_brand, swatches (the first six hex
colors, for previews) and file. Each DESIGN.md starts with "# <title>", a "> Category: <name>" line and a one-line description (one or more
"> " lines). Source: plugin87/ux-ui-agent-skills, design-systems/library/ (MIT, Workflow_References/licenses/
plugin87_ux-ui-agent-skills.txt). inspired_by_brand marks styles named after a company or product: the intake
says "inspired by" for them and never copies the company's identity (Style_Library/README.md).
"""
import argparse
import json
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIB = ROOT / "Style_Library"
INDEX = LIB / "styles.json"

# Categories whose entries are all named after a company or product.
BRAND_CATEGORIES = {
    "AI & LLM", "Automotive", "Backend & Data", "Design & Creative", "Developer Tools",
    "E-Commerce & Retail", "Fintech & Crypto", "Media & Consumer", "Productivity & SaaS",
}
# Named after a product although their category is a generic style.
BRAND_SLUGS = {"ant", "material", "shadcn", "pacman", "tetris"}


def parse(md, slug):
    lines = md.replace("\r", "").split("\n")
    title = next((l[2:].strip() for l in lines if l.startswith("# ")), slug)
    category, desc, i = "", [], 0
    for i, l in enumerate(lines):
        m = re.match(r">\s*Category:\s*(.+)", l)
        if m:
            category = m.group(1).strip()
            break
    for l in lines[i + 1:]:
        if not l.startswith(">"):
            break
        desc.append(l.lstrip("> ").strip())
    name = re.sub(r"^Design System Inspired by\s+", "", title).strip()
    swatches = []  # the first distinct hex colors, in reading order (the palette comes first in every file)
    for h in re.findall(r"#[0-9A-Fa-f]{6}(?![0-9A-Fa-f])", md):
        if h.upper() not in swatches:
            swatches.append(h.upper())
    return {
        "slug": slug,
        "title": title,
        "name": name,
        "category": category,
        "description": " ".join(d for d in desc if d),
        "inspired_by_brand": category in BRAND_CATEGORIES or slug in BRAND_SLUGS,
        "swatches": swatches[:6],
        "file": f"Style_Library/{slug}/DESIGN.md",
    }


def build():
    styles = []
    for f in sorted(LIB.glob("*/DESIGN.md")):
        s = parse(f.read_text(encoding="utf-8"), f.parent.name)
        if not s["category"] or not s["description"]:
            sys.exit(f"{s['file']}: missing the '> Category:' line or the description under the title")
        styles.append(s)
    cats = {}
    for s in styles:
        cats[s["category"]] = cats.get(s["category"], 0) + 1
    return {
        "source": "https://github.com/plugin87/ux-ui-agent-skills/tree/main/design-systems/library",
        "license": "MIT, Copyright (c) 2026 Thientan Soparat (Workflow_References/licenses/plugin87_ux-ui-agent-skills.txt)",
        "note": "Generated by tools/build_style_index.py; do not edit by hand.",
        "count": len(styles),
        "categories": [{"name": k, "count": v} for k, v in sorted(cats.items())],
        "styles": styles,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", help="folder with <slug>/DESIGN.md files to copy in first")
    ap.add_argument("--check", action="store_true", help="exit 1 when styles.json is out of date")
    a = ap.parse_args()
    if a.source:
        src = pathlib.Path(a.source)
        n = 0
        for f in sorted(src.glob("*/DESIGN.md")):
            dest = LIB / f.parent.name / "DESIGN.md"
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(f, dest)
            n += 1
        print(f"copied {n} DESIGN.md files")
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    if a.check:
        ok = INDEX.exists() and INDEX.read_text(encoding="utf-8") == text
        print("styles.json is up to date" if ok else "styles.json is out of date: run python tools/build_style_index.py")
        return 0 if ok else 1
    INDEX.write_text(text, encoding="utf-8")
    data = json.loads(text)
    print(f"{data['count']} styles in {len(data['categories'])} categories -> Style_Library/styles.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
